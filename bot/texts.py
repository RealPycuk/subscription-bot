def tr(lang: str, key: str, **kw) -> str:
    s = T.get(lang, T[DEFAULT_LANG]).get(key) or T[DEFAULT_LANG][key]
    return s.format(**kw) if kw else s


def pick_lang(code: str | None) -> str:
    code = (code or "").lower()[:2]
    if code in ("ru", "uk", "be", "kk"):
        return "ru"
    if code == "es":
        return "es"
    return "en" if code else DEFAULT_LANG


def plan_title(lang: str, plan: dict) -> str:
    return PLAN_TITLES.get(lang, PLAN_TITLES[DEFAULT_LANG]).get(plan["days"]) or plan.get("title") or f"{plan['days']} d"
